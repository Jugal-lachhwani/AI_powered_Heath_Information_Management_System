from __future__ import annotations

from typing import List

from pydantic import BaseModel, Field


class StrictBaseModel(BaseModel):
    class Config:
        extra = "ignore"


class Section(StrictBaseModel):
    text: str = ""
    items: List[str] = Field(default_factory=list)
    suggestions: List[str] = Field(default_factory=list)


class VitalSign(StrictBaseModel):
    label: str = ""
    value: str = ""
    unit: str = ""


class Medication(StrictBaseModel):
    medicine: str = ""
    dose: str = ""
    route: str = ""
    frequency: str = ""
    duration: str = ""
    remarks: str = ""


class ICD10Code(StrictBaseModel):
    code: str = ""
    description: str = ""


class DiagnosisSection(Section):
    icd10: List[ICD10Code] = Field(default_factory=list)


class ClinicalExaminationSection(Section):
    vitals: List[VitalSign] = Field(default_factory=list)
    general_examination: str = ""
    systemic_examination: str = ""


class PrescriptionSection(Section):
    medications: List[Medication] = Field(default_factory=list)


class FollowUpSection(Section):
    date_text: str = ""
    instruction: str = ""


class ClinicalExtraction(StrictBaseModel):
    chief_complaint: Section = Field(default_factory=Section)
    history_of_present_illness: Section = Field(default_factory=Section)
    past_history: Section = Field(default_factory=Section)
    family_history: Section = Field(default_factory=Section)
    drug_allergy: Section = Field(default_factory=Section)
    clinical_examination: ClinicalExaminationSection = Field(
        default_factory=ClinicalExaminationSection
    )
    diagnosis: DiagnosisSection = Field(default_factory=DiagnosisSection)
    investigations: Section = Field(default_factory=Section)
    prescription: PrescriptionSection = Field(default_factory=PrescriptionSection)
    advice: Section = Field(default_factory=Section)
    follow_up: FollowUpSection = Field(default_factory=FollowUpSection)


class TranscriptRequest(StrictBaseModel):
    transcript: str = Field(
        ...,
        min_length=1,
        description="Doctor consultation transcript generated by speech-to-text.",
    )
